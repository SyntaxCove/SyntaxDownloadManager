function harness(settings: Partial<typeof SETTINGS_DEFAULTS> = {}): {
  router: IpcRouter;
  shown: Array<{ title: string; body: string }>;
  port: OsNotificationPort;
} {
  const router = new IpcRouter();
  const shown: Array<{ title: string; body: string }> = [];
  const port: OsNotificationPort = {
    supported: () => true,
    show: (input) => shown.push(input),
  };
  registerNotifyEngine(router, {
    port,
    settings: { settings: { ...SETTINGS_DEFAULTS, ...settings } } as unknown as SettingsStore,
  });
  return { router, shown, port };
}

const emitJob = (router: IpcRouter, event: "download.updated" | "media.updated" | "torrent.updated", job: unknown): void => {
  router.emit(event, EVENTS[event].payload, { job });
};

describe("notify engine (Phase 17)", () => {
  it("notifies a download completing exactly once", () => {
    const { router, shown } = harness();
    const id = newUlid();
    emitJob(router, "download.updated", downloadJob(id, "queued"));
    emitJob(router, "download.updated", downloadJob(id, "downloading"));
    expect(shown).toEqual([]);
    emitJob(router, "download.updated", downloadJob(id, "completed", "/tmp/setup.exe"));
    expect(shown).toEqual([{ title: "Download completed", body: "setup.exe" }]);
    // repeat terminal snapshots and later failures stay silent
    emitJob(router, "download.updated", downloadJob(id, "completed", "/tmp/setup.exe"));
    emitJob(router, "download.updated", downloadJob(id, "failed"));
    expect(shown).toHaveLength(1);
  });

  it("notifies failures with the classified error code", () => {
    const { router, shown } = harness();
    const id = newUlid();
    emitJob(router, "download.updated", downloadJob(id, "downloading"));
    emitJob(router, "download.updated", downloadJob(id, "failed"));
    expect(shown).toEqual([{ title: "Download failed", body: "f.bin — network_error" }]);
  });

  it("canceled and boot snapshots stay silent", () => {
    const { router, shown } = harness();
    emitJob(router, "download.updated", downloadJob(newUlid(), "completed")); // unknown prev
    const id = newUlid();
    emitJob(router, "download.updated", downloadJob(id, "downloading"));
    emitJob(router, "download.updated", downloadJob(id, "canceled"));
    expect(shown).toEqual([]);
  });

  it("torrents fire on the seeding transition and never on completed", () => {
    const { router, shown } = harness();
    const id = newUlid();
    emitJob(router, "torrent.updated", torrentJob(id, "downloading"));
    emitJob(router, "torrent.updated", torrentJob(id, "seeding"));
    expect(shown).toEqual([{ title: "Torrent finished", body: "Sample Torrent" }]);
    emitJob(router, "torrent.updated", torrentJob(id, "seeding"));
    // Removal-time `completed` never notifies (and removal while downloading is silent).
    emitJob(router, "torrent.updated", torrentJob(id, "completed"));
    expect(shown).toHaveLength(1);
    const other = newUlid();
    emitJob(router, "torrent.updated", torrentJob(other, "downloading"));
    emitJob(router, "torrent.updated", torrentJob(other, "completed"));
    expect(shown).toHaveLength(1);
  });

  it("media fires on completed with the title", () => {
    const { router, shown } = harness();
    const id = newUlid();
    emitJob(router, "media.updated", mediaJob(id, "muxing"));
    emitJob(router, "media.updated", mediaJob(id, "completed"));
    expect(shown).toEqual([{ title: "Media ready", body: "Sample Video" }]);
  });

  it("settings gates suppress live (notifyOnComplete off, notifyOnFailure on)", () => {
    const { router, shown } = harness({ notifyOnComplete: false });
    const id = newUlid();
    emitJob(router, "download.updated", downloadJob(id, "downloading"));
    emitJob(router, "download.updated", downloadJob(id, "completed", "/tmp/a.bin"));
    expect(shown).toEqual([]);
    const failedId = newUlid();
    emitJob(router, "download.updated", downloadJob(failedId, "downloading"));
    emitJob(router, "download.updated", downloadJob(failedId, "failed"));
    expect(shown).toEqual([{ title: "Download failed", body: "f.bin — network_error" }]);
  });

  it("an unsupported OS surface never calls show", () => {
    const { router, shown, port } = harness();
    const spy = vi.spyOn(port, "supported").mockReturnValue(false);
    const id = newUlid();
    emitJob(router, "download.updated", downloadJob(id, "downloading"));
    emitJob(router, "download.updated", downloadJob(id, "completed", "/tmp/a.bin"));
    expect(shown).toEqual([]);
    spy.mockRestore();
  });

  it("describeTransition builds domain-specific strings", () => {
    expect(describeTransition("download", "completed", downloadJob(newUlid(), "completed", "/a/b/c.zip")))
      .toEqual({ title: "Download completed", body: "c.zip" });
    expect(describeTransition("media", "failed", mediaJob(newUlid(), "failed")))
      .toEqual({ title: "Media job failed", body: "Sample Video" });
    expect(describeTransition("torrent", "failed", { ...torrentJob(newUlid(), "failed"), errorCode: "proxy_profile_not_found" }))
      .toEqual({ title: "Torrent failed", body: "Sample Torrent — proxy_profile_not_found" });
  });

  it("describeTransition localizes titles for fa while bodies stay user data (Phase 21)", () => {
    expect(describeTransition("download", "completed", downloadJob(newUlid(), "completed", "/a/b/c.zip"), "fa"))
      .toEqual({ title: "دریافت کامل شد", body: "c.zip" });
    expect(describeTransition("media", "failed", mediaJob(newUlid(), "failed"), "fa").title)
      .toBe("کار رسانه ناموفق بود");
    // unknown domain falls back to the English table rather than undefined
    expect(describeTransition("download", "completed", downloadJob(newUlid(), "completed", "/a/b.zip"), "fa").title)
      .not.toBe("");
  });
});
