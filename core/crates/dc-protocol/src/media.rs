//! Media domain (Phase 11, v1.6) — mirrors packages/contracts/src/domain/media.ts.
//!
//! The core runs the bundled yt-dlp (`--dump-single-json`) and projects its JSON into a
//! `MediaManifest` — the exact wire shape the renderer consumes. Normalization rules live in
//! `download-core/src/media.rs`; this module only defines the wire types.

use serde::{Deserialize, Serialize};

/// One selectable video format (DASH video-only or progressive with embedded audio).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct VideoFormat {
    #[serde(rename = "formatId")]
    pub format_id: String,
    pub container: String,
    pub extension: String,
    pub width: Option<u64>,
    pub height: Option<u64>,
    pub fps: Option<f64>,
    pub vcodec: String,
    /// Audio codec embedded in the video file (progressive formats); null = video-only.
    pub acodec: Option<String>,
    #[serde(rename = "vbitrateBps")]
    pub vbitrate_bps: Option<u64>,
    #[serde(rename = "fileSizeBytes")]
    pub file_size_bytes: Option<u64>,
}

/// One selectable audio-only format.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct AudioFormat {
    #[serde(rename = "formatId")]
    pub format_id: String,
    pub container: String,
    pub extension: String,
    pub acodec: String,
    #[serde(rename = "abitrateBps")]
    pub abitrate_bps: Option<u64>,
    #[serde(rename = "sampleRateHz")]
    pub sample_rate_hz: Option<u64>,
    pub channels: Option<u64>,
    #[serde(rename = "fileSizeBytes")]
    pub file_size_bytes: Option<u64>,
}

/// One selectable subtitle track (manual or automatic).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SubtitleTrack {
    #[serde(rename = "formatId")]
    pub format_id: String,
    pub language: String,
    pub title: Option<String>,
    pub extension: String,
    #[serde(rename = "isAutoGenerated")]
    pub is_auto_generated: bool,
}

/// Normalized manifest for one media item — the `media.inspect` result payload.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct MediaManifest {
    #[serde(rename = "sourceUrl")]
    pub source_url: String,
    pub extractor: String,
    pub title: String,
    #[serde(rename = "durationSeconds")]
    pub duration_seconds: Option<f64>,
    #[serde(rename = "webpageUrl")]
    pub webpage_url: String,
    #[serde(rename = "thumbnailUrl")]
    pub thumbnail_url: Option<String>,
    #[serde(rename = "isLive")]
    pub is_live: bool,
    pub videos: Vec<VideoFormat>,
    pub audios: Vec<AudioFormat>,
    pub subtitles: Vec<SubtitleTrack>,
}

/// `media.inspect` params.
#[derive(Debug, Clone, PartialEq, Eq, Deserialize)]
pub struct MediaInspectParams {
    pub url: String,
    #[serde(rename = "proxyProfileId")]
    pub proxy_profile_id: Option<String>,
}

/// `media.inspect` result.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct MediaInspectResult {
    pub manifest: MediaManifest,
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn round_trips_camel_case_wire_shape() {
        let manifest = MediaManifest {
            source_url: "https://example.com/watch/abc".into(),
            extractor: "yt-dlp".into(),
            title: "Sample Video".into(),
            duration_seconds: Some(212.5),
            webpage_url: "https://example.com/watch/abc".into(),
            thumbnail_url: Some("https://example.com/thumbs/abc.jpg".into()),
            is_live: false,
            videos: vec![VideoFormat {
                format_id: "137".into(),
                container: "mp4".into(),
                extension: "mp4".into(),
                width: Some(1920),
                height: Some(1080),
                fps: Some(30.0),
                vcodec: "avc1.640028".into(),
                acodec: None,
                vbitrate_bps: Some(4_500_000),
                file_size_bytes: Some(118_000_000),
            }],
            audios: vec![AudioFormat {
                format_id: "140".into(),
                container: "m4a".into(),
                extension: "m4a".into(),
                acodec: "mp4a.40.2".into(),
                abitrate_bps: Some(128_000),
                sample_rate_hz: Some(44_100),
                channels: Some(2),
                file_size_bytes: Some(3_400_000),
            }],
            subtitles: vec![SubtitleTrack {
                format_id: "vtt-en".into(),
                language: "en".into(),
                title: Some("English".into()),
                extension: "vtt".into(),
                is_auto_generated: false,
            }],
        };
        let json = serde_json::to_value(&manifest).unwrap();
        assert_eq!(json["sourceUrl"], "https://example.com/watch/abc");
        assert_eq!(json["isLive"], false);
        assert_eq!(json["videos"][0]["formatId"], "137");
        assert_eq!(json["videos"][0]["vbitrateBps"], 4_500_000);
        assert!(json["videos"][0].get("acodec").is_some());
        assert_eq!(json["audios"][0]["abitrateBps"], 128_000);
        assert_eq!(json["subtitles"][0]["isAutoGenerated"], false);
        let back: MediaManifest = serde_json::from_value(json).unwrap();
        assert_eq!(back, manifest);
    }

    #[test]
    fn inspect_params_accept_optional_proxy() {
        let p: MediaInspectParams =
            serde_json::from_str(r#"{"url": "https://example.com/watch/abc"}"#).unwrap();
        assert!(p.proxy_profile_id.is_none());
        let p: MediaInspectParams = serde_json::from_str(
            r#"{"url": "https://example.com/watch/abc", "proxyProfileId": "01HQ"}"#,
        )
        .unwrap();
        assert_eq!(p.proxy_profile_id.as_deref(), Some("01HQ"));
    }
}
