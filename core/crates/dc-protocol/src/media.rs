/// A persistent media pipeline job — mirrors the TS `MediaJob` wire shape.
///
/// Wire rules as in `DownloadJob`: fields declared `.nullable()` in zod are ALWAYS
/// serialized (None → null); `Option` fields that are plain optional are omitted when None.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct MediaJob {
    pub id: Ulid,
    #[serde(rename = "sourceUrl")]
    pub source_url: String,
    /// Filled by the first extraction; null until then (always serialized).
    pub title: Option<String>,
    #[serde(rename = "thumbnailUrl")]
    pub thumbnail_url: Option<String>,
    /// Selected yt-dlp format ids; null = not selected (always serialized).
    #[serde(rename = "videoFormatId")]
    pub video_format_id: Option<String>,
    #[serde(rename = "audioFormatId")]
    pub audio_format_id: Option<String>,
    /// Explicit base filename from creation params (omitted when none was given).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub filename: Option<String>,
    /// v1.18 (Phase 33): request headers persisted with the job so every run
    /// re-authenticates (omitted when none were given).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub headers: Option<MediaHeaderMap>,
    pub subtitles: Vec<MediaSubtitleSelection>,
    pub container: MediaContainer,
    #[serde(rename = "destinationDir")]
    pub destination_dir: String,
    /// Final file path; null until the mux renames it into place (always serialized).
    #[serde(rename = "destinationPath")]
    pub destination_path: Option<String>,
    /// Private scratch dir; null until the first run (always serialized).
    #[serde(rename = "workDir")]
    pub work_dir: Option<String>,
    pub status: String,
    /// Sum of the selected stream sizes from the fresh manifest; null while unknown.
    #[serde(rename = "totalBytes")]
    pub total_bytes: Option<u64>,
    #[serde(rename = "receivedBytes")]
    pub received_bytes: u64,
    #[serde(rename = "speedBps")]
    pub speed_bps: Option<u64>,
    #[serde(rename = "etaSeconds")]
    pub eta_seconds: Option<u64>,
    #[serde(rename = "errorCode")]
    pub error_code: Option<String>,
    #[serde(rename = "proxyProfileId")]
    pub proxy_profile_id: Option<String>,
    #[serde(rename = "createdAt")]
    pub created_at: i64,
    #[serde(rename = "updatedAt")]
    pub updated_at: i64,
}

