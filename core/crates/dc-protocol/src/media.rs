// ---- v1.18 (Phase 33): browser-context request headers ----

/// Browser-context request headers (User-Agent / Referer / Cookie …). A `BTreeMap` so
/// the wire JSON and the yt-dlp argv are byte-deterministic regardless of insertion
/// order — the same property `DownloadJob::headers` gets from its persisted JSON.
pub type MediaHeaderMap = std::collections::BTreeMap<String, String>;

/// Hard cap on headers per request (mirrors the zod `MediaHeaders` refine).
pub const MEDIA_HEADERS_MAX: usize = 16;

/// RFC 7230 token characters — the same rule the zod schema enforces on the TS side.
fn is_header_token(name: &str) -> bool {
    !name.is_empty()
        && name.len() <= 128
        && name
            .bytes()
            .all(|b| matches!(b, b'!' | b'#'..=b'\'' | b'*' | b'+' | b'-' | b'.' | b'^' | b'_' | b'`' | b'|' | b'~' | b'0'..=b'9' | b'A'..=b'Z' | b'a'..=b'z'))
}

/// Validate a header map at the core boundary (defense in depth: the zod schema already
/// enforced this on the TS side; the core repeats it before anything reaches argv).
pub fn validate_media_headers(headers: &MediaHeaderMap) -> Result<(), ContractError> {
    if headers.len() > MEDIA_HEADERS_MAX {
        return Err(ContractError::new(
            ErrorCode::InvalidParams,
            format!("at most {MEDIA_HEADERS_MAX} headers are supported"),
        ));
    }
    for (name, value) in headers {
        if !is_header_token(name) {
            return Err(ContractError::new(
                ErrorCode::InvalidParams,
                format!("header name must be an HTTP token: {name}"),
            ));
        }
        if value.is_empty() || value.len() > 4096 || value.contains(['\r', '\n', '\0']) {
            return Err(ContractError::new(
                ErrorCode::InvalidParams,
                format!("header value for {name} must be 1..=4096 chars without CR/LF/NUL"),
            ));
        }
    }
    Ok(())
}

/// Flat yt-dlp argv for the headers (`--add-header "Name: Value"`, repeatable, sorted
/// by name for determinism). Empty input yields no args — absent headers stay absent.
pub fn add_header_args(headers: &MediaHeaderMap) -> Vec<String> {
    let mut args = Vec::with_capacity(headers.len() * 2);
    for (name, value) in headers {
        args.push("--add-header".to_string());
        args.push(format!("{name}: {value}"));
    }
    args
}

