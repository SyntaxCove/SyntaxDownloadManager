/// One selected subtitle track, identified the way yt-dlp consumes it at download time.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct MediaSubtitleSelection {
    pub language: String,
    pub extension: String,
    #[serde(rename = "isAutoGenerated")]
    pub is_auto_generated: bool,
}

/// Mux target container.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum MediaContainer {
    Mkv,
    Mp4,
}

impl MediaContainer {
    pub fn as_str(&self) -> &'static str {
        match self {
            MediaContainer::Mkv => "mkv",
            MediaContainer::Mp4 => "mp4",
        }
    }

    /// ffmpeg output format name for the container.
    pub fn mux_format(&self) -> &'static str {
        match self {
            MediaContainer::Mkv => "matroska",
            MediaContainer::Mp4 => "mp4",
        }
    }

    /// Subtitle codec used inside the container (streams are never re-encoded; subs convert).
    pub fn subtitle_codec(&self) -> &'static str {
        match self {
            MediaContainer::Mkv => "srt",
            MediaContainer::Mp4 => "mov_text",
        }
    }
}

/// Media job lifecycle statuses (mirrors `MediaJobStatus` in the TS contracts).
pub const MEDIA_JOB_STATUSES: [&str; 8] = [
    "queued",
    "extracting",
    "downloading",
    "muxing",
    "paused",
    "completed",
    "failed",
    "canceled",
];

/// A persistent media pipeline job — mirrors the TS `MediaJob` wire shape.
///
/// Wire rules as in `DownloadJob`: fields declared `.nullable()` in zod are ALWAYS
/// serialized (None → null); `Option` fields that are plain optional are omitted when None.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct MediaJob {
    pub id: Ulid,
    #[serde(rename = "sourceUrl")]
    pub source_url: String,
    /// Filled by the first extraction; null until then (always serialized).
    pub title: Option<String>,
    #[serde(rename = "thumbnailUrl")]
    pub thumbnail_url: Option<String>,
    /// Selected yt-dlp format ids; null = not selected (always serialized).
    #[serde(rename = "videoFormatId")]
    pub video_format_id: Option<String>,
    #[serde(rename = "audioFormatId")]
    pub audio_format_id: Option<String>,
    /// Explicit base filename from creation params (omitted when none was given).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub filename: Option<String>,
    pub subtitles: Vec<MediaSubtitleSelection>,
    pub container: MediaContainer,
    #[serde(rename = "destinationDir")]
    pub destination_dir: String,
    /// Final file path; null until the mux renames it into place (always serialized).
    #[serde(rename = "destinationPath")]
    pub destination_path: Option<String>,
    /// Private scratch dir; null until the first run (always serialized).
    #[serde(rename = "workDir")]
    pub work_dir: Option<String>,
    pub status: String,
    /// Sum of the selected stream sizes from the fresh manifest; null while unknown.
    #[serde(rename = "totalBytes")]
    pub total_bytes: Option<u64>,
    #[serde(rename = "receivedBytes")]
    pub received_bytes: u64,
    #[serde(rename = "speedBps")]
    pub speed_bps: Option<u64>,
    #[serde(rename = "etaSeconds")]
    pub eta_seconds: Option<u64>,
    #[serde(rename = "errorCode")]
    pub error_code: Option<String>,
    #[serde(rename = "proxyProfileId")]
    pub proxy_profile_id: Option<String>,
    #[serde(rename = "createdAt")]
    pub created_at: i64,
    #[serde(rename = "updatedAt")]
    pub updated_at: i64,
}

/// `media.download` params (camelCase wire, mirrors the zod schema with its refinements).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct MediaDownloadParams {
    pub url: String,
    #[serde(rename = "videoFormatId", skip_serializing_if = "Option::is_none")]
    pub video_format_id: Option<String>,
    #[serde(rename = "audioFormatId", skip_serializing_if = "Option::is_none")]
    pub audio_format_id: Option<String>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub subtitles: Vec<MediaSubtitleSelection>,
    #[serde(default = "default_container")]
    pub container: MediaContainer,
    #[serde(rename = "destinationDir")]
    pub destination_dir: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub filename: Option<String>,
    #[serde(rename = "proxyProfileId", skip_serializing_if = "Option::is_none")]
    pub proxy_profile_id: Option<String>,
}

fn default_container() -> MediaContainer {
    MediaContainer::Mkv
}

/// `media.download` result.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct MediaDownloadResult {
    pub job: MediaJob,
}

/// `media.list` result.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct MediaListResult {
    pub jobs: Vec<MediaJob>,
}

/// `media.remove` params.
#[derive(Debug, Clone, PartialEq, Eq, Deserialize)]
pub struct MediaRemoveParams {
    pub id: String,
    #[serde(rename = "deleteFiles", default)]
    pub delete_files: bool,
}

/// Throttled pipeline progress payload (`media.progress` event).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct MediaProgress {
    #[serde(rename = "jobId")]
    pub job_id: String,
    /// Mirrors the active MediaJobStatus: extracting | downloading | muxing.
    pub phase: String,
    #[serde(rename = "receivedBytes")]
    pub received_bytes: u64,
    #[serde(rename = "totalBytes")]
    pub total_bytes: Option<u64>,
    #[serde(rename = "speedBps")]
    pub speed_bps: u64,
    #[serde(rename = "etaSeconds")]
    pub eta_seconds: Option<u64>,
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::Ulid;

    #[test]
    fn round_trips_camel_case_wire_shape() {
        let manifest = MediaManifest {
            source_url: "https://example.com/watch/abc".into(),
            extractor: "yt-dlp".into(),
            title: "Sample Video".into(),
            duration_seconds: Some(212.5),
            webpage_url: "https://example.com/watch/abc".into(),
            thumbnail_url: Some("https://example.com/thumbs/abc.jpg".into()),
            is_live: false,
            videos: vec![VideoFormat {
                format_id: "137".into(),
                container: "mp4".into(),
                extension: "mp4".into(),
                width: Some(1920),
                height: Some(1080),
                fps: Some(30.0),
                vcodec: "avc1.640028".into(),
                acodec: None,
                vbitrate_bps: Some(4_500_000),
                file_size_bytes: Some(118_000_000),
            }],
            audios: vec![AudioFormat {
                format_id: "140".into(),
                container: "m4a".into(),
                extension: "m4a".into(),
                acodec: "mp4a.40.2".into(),
                abitrate_bps: Some(128_000),
                sample_rate_hz: Some(44_100),
                channels: Some(2),
                file_size_bytes: Some(3_400_000),
            }],
            subtitles: vec![SubtitleTrack {
                format_id: "vtt-en".into(),
                language: "en".into(),
                title: Some("English".into()),
                extension: "vtt".into(),
                is_auto_generated: false,
            }],
        };
        let json = serde_json::to_value(&manifest).unwrap();
        assert_eq!(json["sourceUrl"], "https://example.com/watch/abc");
        assert_eq!(json["isLive"], false);
        assert_eq!(json["videos"][0]["formatId"], "137");
        assert_eq!(json["videos"][0]["vbitrateBps"], 4_500_000);
        assert!(json["videos"][0].get("acodec").is_some());
        assert_eq!(json["audios"][0]["abitrateBps"], 128_000);
        assert_eq!(json["subtitles"][0]["isAutoGenerated"], false);
        let back: MediaManifest = serde_json::from_value(json).unwrap();
        assert_eq!(back, manifest);
    }

    #[test]
    fn inspect_params_accept_optional_proxy() {
        let p: MediaInspectParams =
            serde_json::from_str(r#"{"url": "https://example.com/watch/abc"}"#).unwrap();
        assert!(p.proxy_profile_id.is_none());
        let p: MediaInspectParams = serde_json::from_str(
            r#"{"url": "https://example.com/watch/abc", "proxyProfileId": "01HQ"}"#,
        )
        .unwrap();
        assert_eq!(p.proxy_profile_id.as_deref(), Some("01HQ"));
    }

    #[test]
    fn media_job_round_trips_camel_case_wire_shape() {
        let job = MediaJob {
            id: Ulid("01JD8W3G5XQ9V4M2K7PZ6N8S0V".into()),
            source_url: "https://example.com/watch/abc".into(),
            title: Some("Sample Video".into()),
            thumbnail_url: Some("https://example.com/thumbs/abc.jpg".into()),
            video_format_id: Some("137".into()),
            audio_format_id: Some("140".into()),
            filename: None,
            subtitles: vec![MediaSubtitleSelection {
                language: "en".into(),
                extension: "vtt".into(),
                is_auto_generated: false,
            }],
            container: MediaContainer::Mkv,
            destination_dir: "/home/user/Downloads".into(),
            destination_path: None,
            work_dir: Some("/home/user/Downloads/.unidm-media/01JD8W3G5XQ9V4M2K7PZ6N8S0V".into()),
            status: "downloading".into(),
            total_bytes: Some(121_400_000),
            received_bytes: 60_700_000,
            speed_bps: Some(2_097_152),
            eta_seconds: Some(29),
            error_code: None,
            proxy_profile_id: None,
            created_at: 1_735_689_600_000,
            updated_at: 1_735_689_900_000,
        };
        let json = serde_json::to_value(&job).unwrap();
        assert_eq!(json["sourceUrl"], "https://example.com/watch/abc");
        assert_eq!(json["videoFormatId"], "137");
        assert_eq!(json["container"], "mkv");
        assert_eq!(json["subtitles"][0]["isAutoGenerated"], false);
        assert!(json["destinationPath"].is_null());
        assert!(json["errorCode"].is_null());
        let back: MediaJob = serde_json::from_value(json).unwrap();
        assert_eq!(back, job);
    }

    #[test]
    fn download_params_default_container_and_omit_empty_subtitles() {
        let p: MediaDownloadParams = serde_json::from_str(
            r#"{"url": "https://example.com/watch/abc", "videoFormatId": "137",
                "destinationDir": "/home/user/Downloads"}"#,
        )
        .unwrap();
        assert_eq!(p.container, MediaContainer::Mkv);
        assert!(p.subtitles.is_empty());
        let json = serde_json::to_value(&p).unwrap();
        assert!(json.get("subtitles").is_none(), "empty subs are omitted");
        assert_eq!(json["container"], "mkv");
    }

    #[test]
    fn container_helpers_map_to_ffmpeg_terms() {
        assert_eq!(MediaContainer::Mkv.mux_format(), "matroska");
        assert_eq!(MediaContainer::Mkv.subtitle_codec(), "srt");
        assert_eq!(MediaContainer::Mp4.mux_format(), "mp4");
        assert_eq!(MediaContainer::Mp4.subtitle_codec(), "mov_text");
        assert_eq!(MediaContainer::Mp4.as_str(), "mp4");
    }

    #[test]
    fn media_progress_round_trips() {
        let raw = serde_json::json!({
            "jobId": "01JD8W3G5XQ9V4M2K7PZ6N8S0V",
            "phase": "muxing",
            "receivedBytes": 121_400_000,
            "totalBytes": null,
            "speedBps": 0,
            "etaSeconds": null,
        });
        let p: MediaProgress = serde_json::from_value(raw.clone()).unwrap();
        assert_eq!(p.phase, "muxing");
        assert_eq!(serde_json::to_value(&p).unwrap(), raw);
    }
}
