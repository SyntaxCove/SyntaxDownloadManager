    #[test]
    fn header_validation_table() {
        let ok = MediaHeaderMap::from([
            ("Cookie".to_string(), "a=1".to_string()),
            ("User-Agent".to_string(), "UA/1.0".to_string()),
        ]);
        assert!(validate_media_headers(&ok).is_ok());

        let bad_name = MediaHeaderMap::from([("X Bad Name".to_string(), "v".to_string())]);
        assert!(validate_media_headers(&bad_name).is_err());
        let colon_name = MediaHeaderMap::from([("X: Injected".to_string(), "v".to_string())]);
        assert!(validate_media_headers(&colon_name).is_err());
        let crlf_value =
            MediaHeaderMap::from([("X-Evil".to_string(), "a\r\nX-Injected: 1".to_string())]);
        assert!(validate_media_headers(&crlf_value).is_err());
        let empty_value = MediaHeaderMap::from([("X-Empty".to_string(), String::new())]);
        assert!(validate_media_headers(&empty_value).is_err());
        let oversized = MediaHeaderMap::from([("X-Big".to_string(), "x".repeat(4097))]);
        assert!(validate_media_headers(&oversized).is_err());
        let too_many: MediaHeaderMap = (0..17)
            .map(|i| (format!("X-H{i}"), "v".to_string()))
            .collect();
        assert!(validate_media_headers(&too_many).is_err());
    }

