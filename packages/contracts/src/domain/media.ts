import { z } from "zod";

/**
 * Media domain data shapes — declared contract-first in v1 (consumed by vitest fixture tests);
 * the IPC methods (media.inspect / extract / download / merge) land with Phases 10–12.
 */

export const VideoFormat = z.object({
  formatId: z.string().min(1),
  container: z.string().min(1),
  extension: z.string().min(1),
  width: z.number().int().positive().nullable(),
  height: z.number().int().positive().nullable(),
  fps: z.number().positive().nullable(),
  vcodec: z.string().min(1),
  vbitrateBps: z.number().int().nonnegative().nullable(),
  fileSizeBytes: z.number().int().nonnegative().nullable(),
});
export type VideoFormat = z.infer<typeof VideoFormat>;

export const AudioFormat = z.object({
  formatId: z.string().min(1),
  container: z.string().min(1),
  extension: z.string().min(1),
  acodec: z.string().min(1),
  abitrateBps: z.number().int().nonnegative().nullable(),
  sampleRateHz: z.number().int().positive().nullable(),
  channels: z.number().int().positive().nullable(),
  fileSizeBytes: z.number().int().nonnegative().nullable(),
});
export type AudioFormat = z.infer<typeof AudioFormat>;

export const SubtitleTrack = z.object({
  formatId: z.string().min(1),
  language: z.string().min(1),
  title: z.string().nullable(),
  extension: z.string().min(1),
  isAutoGenerated: z.boolean().nullable(),
});
export type SubtitleTrack = z.infer<typeof SubtitleTrack>;

export const MediaManifest = z.object({
  sourceUrl: z.string().min(1),
  /** Identifier of the bundled extractor that produced this manifest (e.g. yt-dlp variant). */
  extractor: z.string().min(1),
  title: z.string().min(1),
  durationSeconds: z.number().nonnegative().nullable(),
  webpageUrl: z.string().min(1),
  thumbnailUrl: z.string().nullable(),
  videos: z.array(VideoFormat),
  audios: z.array(AudioFormat),
  subtitles: z.array(SubtitleTrack),
});
export type MediaManifest = z.infer<typeof MediaManifest>;
