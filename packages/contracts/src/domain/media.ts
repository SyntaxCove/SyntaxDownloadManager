import { z } from "zod";
import { Ulid } from "../ids.js";

/**
 * Media domain data shapes — declared contract-first in v1; `media.inspect` (v1.6, Phase 11)
 * is the first method on this domain: the Rust core runs the bundled yt-dlp and projects its
 * JSON into a MediaManifest. v1.7 (Phase 12) adds the persistent media job pipeline:
 * format selection → bundled yt-dlp stream downloads → bundled FFmpeg mux.
 */

export const VideoFormat = z.object({
  formatId: z.string().min(1),
  container: z.string().min(1),
  extension: z.string().min(1),
  width: z.number().int().positive().nullable(),
  height: z.number().int().positive().nullable(),
  fps: z.number().positive().nullable(),
  vcodec: z.string().min(1),
  /** Audio codec embedded in the video file (progressive formats); null = video-only. */
  acodec: z.string().min(1).nullable(),
  vbitrateBps: z.number().int().nonnegative().nullable(),
  fileSizeBytes: z.number().int().nonnegative().nullable(),
});
export type VideoFormat = z.infer<typeof VideoFormat>;

export const AudioFormat = z.object({
  formatId: z.string().min(1),
  container: z.string().min(1),
  extension: z.string().min(1),
  acodec: z.string().min(1),
  abitrateBps: z.number().int().nonnegative().nullable(),
  sampleRateHz: z.number().int().positive().nullable(),
  channels: z.number().int().positive().nullable(),
  fileSizeBytes: z.number().int().nonnegative().nullable(),
});
export type AudioFormat = z.infer<typeof AudioFormat>;

export const SubtitleTrack = z.object({
  formatId: z.string().min(1),
  language: z.string().min(1),
  title: z.string().nullable(),
  extension: z.string().min(1),
  isAutoGenerated: z.boolean().nullable(),
});
export type SubtitleTrack = z.infer<typeof SubtitleTrack>;

export const MediaManifest = z.object({
  sourceUrl: z.string().min(1),
  /** Identifier of the bundled extractor that produced this manifest (e.g. yt-dlp variant). */
  extractor: z.string().min(1),
  title: z.string().min(1),
  durationSeconds: z.number().nonnegative().nullable(),
  webpageUrl: z.string().min(1),
  thumbnailUrl: z.string().nullable(),
  /** Live streams surface honestly; merge/download policy for them is a Phase 12 decision. */
  isLive: z.boolean(),
  videos: z.array(VideoFormat),
  audios: z.array(AudioFormat),
  subtitles: z.array(SubtitleTrack),
});
export type MediaManifest = z.infer<typeof MediaManifest>;

/** `media.inspect` (v1.6, Phase 11) — served by the Rust core. */
export const MediaInspectParams = z.object({
  url: z.string().min(1),
  /** Route the extractor's own traffic through a proxy profile (fail-closed if missing). */
  proxyProfileId: z.string().min(1).optional(),
});
export type MediaInspectParams = z.infer<typeof MediaInspectParams>;

export const MediaInspectResult = z.object({
  manifest: MediaManifest,
});
export type MediaInspectResult = z.infer<typeof MediaInspectResult>;

// ---- v1.7 (Phase 12): persistent media job pipeline ----

/** One selected subtitle track, identified the way yt-dlp consumes it at download time. */
export const MediaSubtitleSelection = z.object({
  language: z.string().min(1),
  extension: z.string().min(1),
  isAutoGenerated: z.boolean(),
});
export type MediaSubtitleSelection = z.infer<typeof MediaSubtitleSelection>;

export const MediaJobStatus = z.enum([
  "queued",
  "extracting",
  "downloading",
  "muxing",
  "paused",
  "completed",
  "failed",
  "canceled",
]);
export type MediaJobStatus = z.infer<typeof MediaJobStatus>;

/** Mux target container. `mkv` accepts every stream; `mp4` transcodes subtitles to mov_text. */
export const MediaContainer = z.enum(["mkv", "mp4"]);
export type MediaContainer = z.infer<typeof MediaContainer>;

/**
 * A persistent media pipeline job. The persistent source is the page URL: every run
 * re-extracts fresh stream data, so an expired extractor URL never destroys the job or
 * the already-downloaded bytes (work-dir `.part` resume + completed-stream skip).
 */
export const MediaJob = z.object({
  id: Ulid,
  sourceUrl: z.string().min(1),
  /** Filled by the first extraction; null until then (the renderer shows the URL). */
  title: z.string().min(1).nullable(),
  thumbnailUrl: z.string().min(1).nullable(),
  /** Selected yt-dlp format ids; null = not selected. At least one is always set. */
  videoFormatId: z.string().min(1).nullable(),
  audioFormatId: z.string().min(1).nullable(),
  /** Explicit base filename from creation params; omitted when none was given. */
  filename: z.string().min(1).nullish(),
  subtitles: z.array(MediaSubtitleSelection).max(8),
  container: MediaContainer,
  destinationDir: z.string().min(1),
  /** Final file path; null until the mux renames it into place. */
  destinationPath: z.string().min(1).nullable(),
  /** Private scratch dir (`<destinationDir>/.syntaxdm-media/<id>/`); null until first run. */
  workDir: z.string().min(1).nullable(),
  status: MediaJobStatus,
  /** Sum of the selected stream sizes from the fresh manifest; null while unknown. */
  totalBytes: z.number().int().nonnegative().nullable(),
  receivedBytes: z.number().int().nonnegative(),
  speedBps: z.number().int().nonnegative().nullable(),
  etaSeconds: z.number().int().nonnegative().nullable(),
  errorCode: z.string().nullable(),
  proxyProfileId: z.string().min(1).nullable(),
  createdAt: z.number().int().nonnegative(),
  updatedAt: z.number().int().nonnegative(),
});
export type MediaJob = z.infer<typeof MediaJob>;

export const MediaDownloadParams = z
  .object({
    url: z.string().min(1),
    videoFormatId: z.string().min(1).optional(),
    audioFormatId: z.string().min(1).optional(),
    subtitles: z.array(MediaSubtitleSelection).max(8).optional(),
    container: MediaContainer.optional().default("mkv"),
    destinationDir: z.string().min(1),
    /** Base filename without extension; default: sanitized page title (filled on extract). */
    filename: z.string().min(1).optional(),
    proxyProfileId: Ulid.nullish(),
  })
  .refine((p) => p.videoFormatId !== undefined || p.audioFormatId !== undefined, {
    message: "select at least one of videoFormatId or audioFormatId",
  })
  .refine((p) => p.subtitles === undefined || p.videoFormatId !== undefined, {
    message: "subtitles require a video format selection",
  });
export type MediaDownloadParams = z.infer<typeof MediaDownloadParams>;

export const MediaDownloadResult = z.object({ job: MediaJob });
export type MediaDownloadResult = z.infer<typeof MediaDownloadResult>;

export const MediaListParams = z.object({});
export const MediaListResult = z.object({ jobs: z.array(MediaJob) });
export type MediaListResult = z.infer<typeof MediaListResult>;

export const MediaJobIdParams = z.object({ id: Ulid });
export const MediaJobByIdResult = z.object({ job: MediaJob.nullable() });
export type MediaJobByIdResult = z.infer<typeof MediaJobByIdResult>;

export const MediaRemoveParams = z.object({
  id: Ulid,
  /** Also delete the work dir (partial streams) and the completed final file. */
  deleteFiles: z.boolean().optional().default(false),
});
export const MediaRemoveResult = z.object({ removed: z.literal(true) });

/** Throttled pipeline progress payload (`media.progress`); bytes carry the stream totals. */
export const MediaProgress = z.object({
  jobId: Ulid,
  /** Mirrors MediaJobStatus: extracting | downloading | muxing while active. */
  phase: z.string().min(1),
  receivedBytes: z.number().int().nonnegative(),
  totalBytes: z.number().int().nonnegative().nullable(),
  speedBps: z.number().int().nonnegative(),
  etaSeconds: z.number().int().nonnegative().nullable(),
});
export type MediaProgress = z.infer<typeof MediaProgress>;
