#!/usr/bin/env bash
# Byte-level acceptance for release v1.2.0 (same procedure as v1.0.0 / v1.1.0).
set -euo pipefail
T=$(sed -n 's/^Token:[[:space:]]*//p' /home/z/my-project/upload/Github.txt | tr -d '[:space:]')
DIR=/home/z/my-project/tool-results/v1.2.0-accept
mkdir -p "$DIR"; cd "$DIR"

ASSETS=(
  latest.yml
  latest.yml.sha256
  SyntaxDownloadManager-1.2.0-portable.zip
  SyntaxDownloadManager-1.2.0-portable.zip.sha256
  SyntaxDownloadManager-1.2.0-sbom.cdx.json
  SyntaxDownloadManager-1.2.0-sbom.cdx.json.sha256
  SyntaxDownloadManager-Setup-1.2.0.exe
  SyntaxDownloadManager-Setup-1.2.0.exe.sha256
  SyntaxDownloadManager-Setup-1.2.0.exe.blockmap
  SyntaxDownloadManager-Setup-1.2.0.exe.blockmap.sha256
)

for a in "${ASSETS[@]}"; do
  [ -s "$a" ] || curl -sSL -H "Authorization: Bearer $T" \
    -o "$a" "https://github.com/SyntaxCove/SyntaxDownloadManager/releases/download/v1.2.0/$a"
  echo "downloaded: $a ($(stat -c%s "$a") B)"
done

echo '=== sha256 sidecar verification ==='
for s in *.sha256; do
  # sidecars are generated by digest util; accept both "hash  name" layouts
  ( sha256sum -c "$s" 2>/dev/null ) || ( cd . && python3 - "$s" <<'PY'
import hashlib,sys,os,re
side=sys.argv[1]; txt=open(side).read()
m=re.search(r'([0-9a-f]{64})',txt)
name=side[:-7] if side.endswith('.sha256') else side[:-len('.sha256')]
h=hashlib.sha256(open(name,'rb').read()).hexdigest()
print(f"{name}: {'OK' if h==m.group(1) else 'FAIL'} (computed {h})")
sys.exit(0 if h==m.group(1) else 1)
PY
)
done

echo '=== latest.yml version ==='
grep -E '^(version|path):' latest.yml

echo '=== SBOM ==='
python3 - <<'PY'
import json
d=json.load(open('SyntaxDownloadManager-1.2.0-sbom.cdx.json'))
print('bomFormat:',d.get('bomFormat'),'specVersion:',d.get('specVersion'))
comp=d.get('metadata',{}).get('component',{})
print('app:',comp.get('name'),comp.get('version'))
print('components:',len(d.get('components',[])))
PY

echo '=== portable zip CRC integrity ==='
python3 - <<'PY'
import zipfile
z=zipfile.ZipFile('SyntaxDownloadManager-1.2.0-portable.zip')
bad=z.testzip()
names=z.namelist()
print('entries:',len(names),'| first bad CRC:',bad)
PY

echo '=== ACCEPTANCE DONE ==='
